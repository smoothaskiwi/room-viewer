import assert from 'node:assert/strict';
import {shape, core, overlaps, gap, support, inside, banquetteSolids} from './shapes.mjs';
const pill=shape({x:15.6,y:54.9,w:48,d:32,h:30,shape:'pill'});
const oval=shape({...pill,shape:'oval'});
const chamfer=[17.6,77.3,25.2,84.9];
const overlap=s=>(support(s,[-1,1])-59.7)/Math.SQRT2;
assert.ok(Math.abs(overlap(pill)-1.58)<.03);
assert.ok(overlap(oval)<overlap(pill),'oval corner less intrusive than pill');
assert.ok(overlap(shape({...pill,shape:'rectangle'}))>8);
assert.ok(Math.abs(core(pill).area()-(16*32+Math.PI*16**2))<1e-6);
const solids=banquetteSolids({west_leg:{x:[0,17.6],y:[36.2,102.4],seat_front_y:[36.2,77.3]},south_leg:{x:[0,66],y:[84.9,102.4],seat_front_x:[25.2,66]},seat_top_z:18,back_top_z:33.7,back_cushion_thickness:4.5});
const foot=shape({x:25.6,y:56.9,w:28,d:28,h:2,shape:'round'});
assert.equal(overlaps(foot,solids[0]),false,'touching round foot at 2-in overlap');
assert.equal(overlaps(shape({...foot,y:57.9}),solids[0]),true,'28-in round foot crosses plinth at 3-in overlap');
assert.equal(overlaps(pill,solids[0]),true,'top can overlap lower seat in plan');
assert.equal(overlaps(pill,solids[1]),false,'top clears tall back');
assert.ok(Math.abs(gap(shape({x:25.6,y:62.9,w:28,d:16,shape:'rectangle'}),solids[0]).distance-6.4/Math.SQRT2)<1e-6,'chamfer is closer than either straight seat front');
assert.equal(inside(shape({x:1,y:1,w:2,d:2}),[[0,0],[10,0],[10,10],[0,10]]),true);
assert.equal(inside(shape({x:8,y:8,w:4,d:4}),[[0,0],[10,0],[10,10],[0,10]]),false);
console.log('PASS flatten shape fixtures: pill/oval/chamfer, exact arc area, pedestal/plinth, polygon containment');
